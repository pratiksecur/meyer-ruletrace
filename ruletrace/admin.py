"""What an administrator needs on one screen: who can do what, who has been doing what, and whether the system is healthy.

Pure data in, plain data out (no database or web code), built only from recorded audit entries, the role map and
the rule pack. Nothing here is estimated or generated by a model."""

from __future__ import annotations

from collections import Counter

CAPABILITIES = {
    "engineer": {"label": "Engineers", "can": ["Upload and check designs", "See element-level findings", "Use the AI helpers",
                                               "Read the organisation posture and the audit record"]},
    "compliance": {"label": "Compliance (CISO)", "can": ["Read the organisation posture", "Read the audit record",
                                                        "Cannot upload or check designs (read-only)"]},
    "executive": {"label": "Executives", "can": ["See the plain summary and money figures",
                                                 "No findings, no posture, no audit record"]},
}
CHECK = "design.checked"


def build_admin(entries: list[dict], views: dict, administrators: list[str], rules: list, designs_stored: int,
                chain: dict, llm: dict, days: int = 14) -> dict:
    roles = [{"view": v, "label": CAPABILITIES[v]["label"], "roles": list(views.get(v) or []), "can": CAPABILITIES[v]["can"]}
             for v in CAPABILITIES]

    people: dict[str, dict] = {}
    for e in entries:
        a = people.setdefault(e.get("actor") or "unknown", {"actor": e.get("actor") or "unknown", "checks": 0, "ai": 0, "last_seen": None})
        a["checks" if e["action"] == CHECK else "ai"] += 1
        a["last_seen"] = e["ts"] if a["last_seen"] is None or str(e["ts"]) > str(a["last_seen"]) else a["last_seen"]
    people_rows = sorted(people.values(), key=lambda a: (-(a["checks"] + a["ai"]), a["actor"]))

    per_day: dict[str, Counter] = {}
    for e in entries:
        per_day.setdefault(str(e["ts"])[:10], Counter())["checks" if e["action"] == CHECK else "ai"] += 1
    daily = [{"day": d, "checks": c["checks"], "ai": c["ai"]} for d, c in sorted(per_day.items())][-days:]

    unverified = [r for r in rules if not r.verified]
    system = {"rules": len(rules), "rules_unverified": len(unverified), "designs_stored": designs_stored,
              "audit_records": chain.get("entries"), "history_intact": chain.get("ok"),
              "first_broken_seq": chain.get("first_broken_seq"), "llm": llm}
    findings = []
    if chain.get("ok") is False:
        findings.append({"level": "bad", "text": "The check history has been changed. Investigate before anyone relies on it"})
    if not llm.get("reachable"):
        findings.append({"level": "warn", "text": "The local AI model is not reachable. Explanations fall back to the rules' own text"})
    elif not llm.get("model_pulled"):
        findings.append({"level": "warn", "text": f"The AI model '{llm.get('model')}' is not installed on this machine"})
    if unverified:
        findings.append({"level": "warn", "text": f"{len(unverified)} of {len(rules)} rules are not yet verified against the official text"})
    if not views.get("compliance"):
        findings.append({"level": "warn", "text": "No role is mapped to the compliance (CISO) view"})
    if not findings:
        findings.append({"level": "good", "text": "System checks are healthy"})
    return {"roles": roles, "administrators": list(administrators), "people": people_rows, "daily": daily,
            "system": system, "findings": findings}
