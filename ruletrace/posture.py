"""Organisation-wide compliance posture, for the CISO / compliance lead.

Built only from what RuleTrace has recorded: the design checks in the audit chain, the rule pack, and the
AI actions that were logged. Nothing here is estimated or generated by a model. Every number can be traced
to a recorded check, and the rating rule is shown on screen.

This module has no database or web code: it takes the dashboard summary (``dashboard.build_summary``), the
rule pack and a list of audit entries as plain data, so it is easy to test.
"""

from __future__ import annotations

RATING_RULE = ("AT RISK when any major issue is open. WATCH when only minor issues, warnings or checks that "
               "could not be decided remain. CLEAR when nothing is open.")

AI_ACTIONS = {
    "design.explained": "Findings explained",
    "design.fixes_suggested": "Fixes suggested",
    "design.whatif": "What-if questions",
    "rule.drafted": "Rules drafted from text",
    "assistant.asked": "Questions answered",
    "ruleset.analysed": "Rule sets analysed",
}


APPROVAL_STAGES = (("not started", "Not started"), ("in review", "Engineer reviewing"),
                   ("prepared", "Awaiting approval"), ("approved", "Approved"), ("rejected", "Sent back"))


def approvals_of(designs: list[dict]) -> dict:
    """Human sign-off progress across designs: how many are at each stage, and which are waiting for an approver.
    Each design carries ``review`` (see dashboard._review); a design with none counts as not started."""
    stages = {k: 0 for k, _ in APPROVAL_STAGES}
    awaiting = []
    for d in designs:
        rv = d.get("review") or {}
        stage = rv.get("stage") if rv.get("stage") in stages else "not started"
        stages[stage] += 1
        if stage == "prepared":
            awaiting.append({"design_id": d.get("design_id"), "ship": d.get("ship") or d.get("title"), "title": d.get("title"),
                             "prepared_by": rv.get("prepared_by"), "open": rv.get("open", 0)})
    total = len(designs)
    return {"total": total, "approved": stages["approved"], "pct_approved": _pct(stages["approved"], total),
            "stages": [{"stage": k, "label": lbl, "count": stages[k]} for k, lbl in APPROVAL_STAGES], "awaiting": awaiting}


def _plural(n: int, word: str) -> str:
    return f"{n} {word}" + ("" if n == 1 else "s")


def rating(designs: int, major: int, minor: int, warn: int, unknown: int) -> dict:
    if not designs:
        return {"level": "none", "label": "NO CHECKS YET", "reason": "No design has been checked yet.", "rule": RATING_RULE}
    if major:
        reason = f"{_plural(major, 'major issue')} open" + (f", {minor} minor" if minor else "")
        return {"level": "at_risk", "label": "AT RISK", "reason": reason, "rule": RATING_RULE}
    parts = []
    if minor:
        parts.append(_plural(minor, "minor issue"))
    if warn:
        parts.append(_plural(warn, "point") + " to review")
    if unknown:
        parts.append(_plural(unknown, "check") + " that could not be decided")
    if parts:
        return {"level": "watch", "label": "WATCH", "reason": ", ".join(parts), "rule": RATING_RULE}
    return {"level": "clear", "label": "CLEAR", "reason": "No issues found by the checked rules", "rule": RATING_RULE}


def approvals_pending(designs: list[dict]) -> int:
    return sum(1 for d in designs if (d.get("review") or {}).get("stage") == "prepared")


def _pct(part: int, whole: int):
    return round(100 * part / whole) if whole else None


def build_posture(summary: dict, rules: list, entries: list[dict]) -> dict:
    """``summary``: dashboard.build_summary output (before any role redaction).
    ``rules``: Rule objects (id, title, regime, ref, severity, verified).
    ``entries``: audit entries as dicts with seq, ts, actor, action, payload."""
    designs = summary.get("designs", [])
    counts = {k: sum(d.get("counts", {}).get(k, 0) for d in designs) for k in ("pass", "fail", "warn", "unknown")}
    sev = (summary.get("totals") or {}).get("fail_by_severity") or {"major": 0, "minor": 0}
    major, minor = sev.get("major", 0), sev.get("minor", 0)
    decided = counts["pass"] + counts["fail"] + counts["warn"]
    pass_rate, coverage = _pct(counts["pass"], decided), _pct(decided, decided + counts["unknown"])

    # per design, and a short list of where to focus first
    ship_rows = []
    for d in designs:
        fails = d.get("fails") or []
        ship_rows.append({"design_id": d.get("design_id"), "ship": d.get("ship") or d.get("title"), "title": d.get("title"),
                          "readiness": d.get("readiness"), "readiness_label": d.get("readiness_label"),
                          "major": sum(1 for f in fails if f.get("severity") == "major"),
                          "minor": sum(1 for f in fails if f.get("severity") == "minor"),
                          "unknown": d.get("counts", {}).get("unknown", 0),
                          "checked_by": d.get("checked_by"), "checked_at": d.get("checked_at")})
    focus = sorted((r for r in ship_rows if r["major"] or r["minor"] or r["unknown"]),
                   key=lambda r: (-r["major"], -r["minor"], -r["unknown"]))[:5]

    # rules that fail on several ships are systemic, not one-offs
    agg: dict[str, dict] = {}
    for d in designs:
        for f in d.get("fails") or []:
            a = agg.setdefault(f["rule_id"], {"rule_id": f["rule_id"], "title": f.get("title"), "regime": f.get("regime"),
                                              "ref": f.get("ref"), "severity": f.get("severity"), "designs": set(), "elements": 0})
            a["designs"].add(d.get("design_id"))
            a["elements"] += 1
    recurring = sorted(({**a, "designs": len(a["designs"]), "systemic": len(a["designs"]) >= 2} for a in agg.values()),
                       key=lambda a: (-a["designs"], -a["elements"], a["rule_id"]))[:8]

    # rule coverage per regime: how many rules, how many verified against the official text, what is open
    open_by_regime = {g["regime"]: g["fail"] for g in summary.get("regimes", [])}
    affected: dict[str, set] = {}
    for d in designs:
        for f in d.get("fails") or []:
            affected.setdefault(f.get("regime"), set()).add(d.get("design_id"))
    regimes: dict[str, dict] = {}
    for r in rules:
        g = regimes.setdefault(r.regime, {"regime": r.regime, "rules": 0, "verified": 0})
        g["rules"] += 1
        g["verified"] += 1 if r.verified else 0
    regime_rows = sorted(({**g, "open_fail": open_by_regime.get(g["regime"], 0),
                           "designs_affected": len(affected.get(g["regime"], ()))} for g in regimes.values()),
                         key=lambda g: (-g["open_fail"], g["regime"]))
    unverified = [r for r in rules if not r.verified]
    rule_pack = {"rules": len(rules), "verified": len(rules) - len(unverified), "unverified": len(unverified),
                 "unverified_rules": [{"id": r.id, "regime": r.regime, "ref": r.ref} for r in unverified[:10]]}

    # trend over every recorded check, oldest first
    trend = [{"seq": e["seq"], "ts": e["ts"], "file": (e["payload"] or {}).get("file"), "actor": e.get("actor"),
              **{k: ((e["payload"] or {}).get("counts") or {}).get(k, 0) for k in ("fail", "warn", "unknown", "pass")}}
             for e in entries if e["action"] == "design.checked"][-30:]

    # how AI was used, from the audit chain
    by_action = {k: 0 for k in AI_ACTIONS}
    explained = fell_back = drafted_usable = 0
    for e in entries:
        if e["action"] in by_action:
            by_action[e["action"]] += 1
        p = e.get("payload") or {}
        if e["action"] == "design.explained":
            explained += int(p.get("explained") or 0)
            fell_back += int(p.get("fell_back_to_rules") or 0)
        elif e["action"] == "rule.drafted":
            drafted_usable += int(p.get("usable") or 0)
    ai = {"total": sum(by_action.values()), "by_action": [{"action": k, "label": AI_ACTIONS[k], "count": v} for k, v in by_action.items()],
          "explanations": explained, "explanations_fell_back": fell_back,
          "fallback_pct": _pct(fell_back, explained), "rule_drafts_usable": drafted_usable,
          "policy": "The AI never decides compliance. The rule engine does. AI output is checked by code or reviewed by an engineer."}

    chain = summary.get("chain") or {}
    signals = []
    if major:
        signals.append({"level": "bad", "text": f"{_plural(major, 'major issue')} open on {_plural(sum(1 for r in ship_rows if r['major']), 'design')}"})
    if minor:
        signals.append({"level": "warn", "text": f"{_plural(minor, 'minor issue')} open"})
    if counts["unknown"]:
        signals.append({"level": "warn", "text": f"{_plural(counts['unknown'], 'check')} could not be decided because the design lacks a value"})
    if approvals_pending(designs):
        signals.append({"level": "warn", "text": f"{_plural(approvals_pending(designs), 'design')} waiting for an approver's signature"})
    if unverified:
        signals.append({"level": "warn", "text": f"{len(unverified)} of {len(rules)} rules are not yet verified against the official text"})
    if chain.get("ok") is False:
        signals.append({"level": "bad", "text": "The check history has been changed. Do not rely on it until this is explained"})
    elif chain:
        signals.append({"level": "good", "text": f"Check history intact: all {chain.get('entries', 0)} records unchanged"})

    approvals = approvals_of(designs)
    return {"rating": rating(len(designs), major, minor, counts["warn"], counts["unknown"]),
            "outcomes": counts, "approvals": approvals,
            "readiness": {k: sum(1 for r in ship_rows if r["readiness"] == k) for k in ("ready", "review", "fix", "info")},
            "kpis": {"designs": len(designs), "checks_run": (summary.get("totals") or {}).get("checks_run", 0),
                     "major_open": major, "minor_open": minor, "warn_open": counts["warn"], "unknown_open": counts["unknown"],
                     "pass_rate": pass_rate, "coverage": coverage},
            "signals": signals, "ships": ship_rows, "focus": focus, "recurring": recurring, "regimes": regime_rows,
            "rule_pack": rule_pack, "trend": trend, "ai": ai, "chain": chain}
