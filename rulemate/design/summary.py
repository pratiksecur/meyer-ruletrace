"""Plain-language summaries of what was read and checked, for people who are not compliance engineers.

Written by code from the confirmed readings and computed verdicts only: nothing here is generated by a model,
so every sentence is as trustworthy as the numbers behind it. Each summary says what was found, what it means,
and what to do next, also when nothing could be read.
"""

from __future__ import annotations

import re

from .extract import _TEXT_FACTS, drawing_meta, text_facts


def _names(items: list[dict], n: int = 6) -> str:
    seen, out = set(), []
    for x in items:
        name = " ".join(str(x.get("label", "")).split()).title()
        if name and name.lower() not in seen:
            seen.add(name.lower())
            out.append(name)
    more = len(out) - n
    return ", ".join(out[:n]) + (f" and {more} more" if more > 0 else "")


def drawing_facts(words: list) -> dict:
    """Title block and stated facts read from the sheet's own text (OCR)."""
    meta = drawing_meta(words) if words else {}
    text = " ".join(w.text for w in words)
    facts = {f[1]: f[3] for f in text_facts([text])}
    m = re.search(r"ACCOMMODATION\s+FOR\s+(\d+)\s+PERSONS", text, re.I)
    if m:
        facts.setdefault("persons accommodated", float(m.group(1)))
    return {"drawing": meta.get("drawing", ""), "title": meta.get("title", "") or meta.get("view", ""),
            "is_ga": meta.get("is_ga", False), **facts}


def summarize_drawing(items: list[dict], facts: dict, error: str = "") -> dict:
    """items: Gemini readings after code confirmation (dicts with label, kind, berths, confirmed...)."""
    if error:
        return {"headline": "Nothing could be read from this drawing.",
                "points": [_explain_error(error)],
                "next": ["Nothing was checked. Try again later, or try another page of the PDF."]}
    conf = [x for x in items if x.get("confirmed")]
    if not items:
        return {"headline": "Gemini did not find any labelled rooms on this page.",
                "points": ["The page may show no room names (only symbols or numbers), or the text is too small "
                           "or drawn too faintly to read."],
                "next": ["Try another page of the PDF, or a clearer or larger copy of the drawing. "
                         "For written dimensions use the Check values tab."]}
    cabins = [x for x in conf if x.get("kind") == "stateroom"]
    hospital = [x for x in conf if x.get("kind") == "hospital"]
    stated = [x for x in cabins if x.get("berths_confirmed") and x.get("berths")]
    other = [x for x in conf if x.get("kind") not in ("stateroom", "hospital")]
    what = "general arrangement drawing" if facts.get("is_ga") else "drawing"
    ident = f" no. {facts['drawing']}" if facts.get("drawing") else ""
    headline = f"This is a {what}{ident}. RuleMate found {len(conf)} labelled spaces on it."
    points = []
    if facts.get("persons accommodated"):
        points.append(f"The drawing says it has accommodation for {facts['persons accommodated']:g} persons.")
    if cabins:
        txt = f"{len(cabins)} cabin(s) with a readable name: {_names(cabins)}."
        if stated:
            txt += (f" For {len(stated)} of them the drawing states the number of berths "
                    f"({sum(x['berths'] for x in stated):g} berths in total).")
        else:
            txt += " The drawing does not print how many berths each cabin has, so berths cannot be counted from it."
        points.append(txt)
    else:
        points.append("No cabins with a readable name: this sheet may not label its cabins, or they are on another sheet.")
    points.append("A hospital is shown on the drawing." if hospital else "No hospital is labelled on this sheet.")
    if other:
        points.append(f"Other spaces: {_names(other, 8)}.")
    if len(items) > len(conf):
        points.append(f"{len(items) - len(conf)} further reading(s) by Gemini could not be confirmed on the drawing "
                      "and are not used.")
    nxt = []
    if len(cabins) + len(hospital) >= 3:
        nxt.append("Press Check in RuleTrace 3D to see the rooms in 3D and check them against the accommodation rules "
                   "(hospital, berths). Fill in the ship details first: keel date and persons on board decide which rules apply.")
    else:
        nxt.append("Too few rooms were found to check the accommodation in 3D.")
    nxt.append("To check written dimensions (door widths, heights, stair angles) use the Check values tab.")
    return {"headline": headline, "points": points, "next": nxt}


def summarize_check(results: list[dict], docs) -> dict:
    """results: dicts with verdict (PASS / FAIL / NEEDS REVIEW / NO RULE / CHECK INPUT), parameter, value, deciding."""
    if not results:
        return {"headline": "No values were found to check.",
                "points": ["Nothing on this file could be read as a value with a unit."],
                "next": ["Try a clearer picture, another PDF page, or add values by hand."]}
    by = {v: [r for r in results if r["verdict"] == v] for v in ("PASS", "FAIL", "NEEDS REVIEW", "NO RULE", "CHECK INPUT")}
    n = len(results)
    if by["FAIL"]:
        headline = f"{len(by['FAIL'])} of {n} values break a rule."
    elif by["PASS"]:
        headline = f"All {len(by['PASS'])} values that a rule covers meet it."
    else:
        headline = f"None of the {n} values could be judged against the loaded rules."
    points = []
    for r in by["FAIL"][:5]:
        lim = r.get("deciding") or {}
        points.append(f"Too {'small' if '>=' in lim.get('limit', '') else 'large'}: {r['parameter']} is {r['value']}; "
                      f"the rule requires {lim.get('limit', '?').replace('>=', 'at least').replace('<=', 'at most')} "
                      f"({lim.get('clause', '')}).")
    if by["PASS"]:
        points.append(f"Meets the rule: {', '.join(r['parameter'] for r in by['PASS'][:6])}"
                      f"{' and more' if len(by['PASS']) > 6 else ''}.")
    if by["NEEDS REVIEW"]:
        points.append(f"{len(by['NEEDS REVIEW'])} value(s) depend on a condition the drawing does not show "
                      "(for example 'only if two berths are stacked'): an engineer has to confirm it.")
    if by["NO RULE"]:
        points.append(f"{len(by['NO RULE'])} value(s) are not covered by the loaded rules "
                      f"({', '.join(r['parameter'] for r in by['NO RULE'][:4])}): nothing in "
                      f"{', '.join(docs) if isinstance(docs, list) else 'the rule texts'} sets a limit for them.")
    if by["CHECK INPUT"]:
        points.append(f"{len(by['CHECK INPUT'])} value(s) could not be used because the number or unit is unclear "
                      f"({', '.join(str(r['value']) for r in by['CHECK INPUT'][:3])}).")
    nxt = []
    if by["FAIL"]:
        nxt.append("Open a red item to see the clause and where the value came from, then change the design.")
    if by["NO RULE"]:
        nxt.append("To check the 'not covered' values, load the rule set that governs them (for example class rules "
                   "or SOLAS for main dimensions and structure).")
    if by["CHECK INPUT"]:
        nxt.append("Correct the unclear values (add the unit, split combined values) and check again.")
    if not nxt:
        nxt.append("Nothing to fix for these values.")
    return {"headline": headline, "points": points, "next": nxt}


def _explain_error(err: str) -> str:
    e = err.lower()
    if "quota" in e or "429" in e:
        return ("Gemini's free daily allowance is used up for all models right now. It resets during the day; "
                "readings already made are kept and shown again for free.")
    if "timeout" in e or "busy" in e or "503" in e:
        return "Gemini is busy at the moment and did not answer in time."
    if "api key" in e or "gemini_api_key" in e:
        return "No Gemini key is set up (GEMINI_API_KEY in .env)."
    if "page must be" in e:
        return err
    return f"Reading failed: {err[:160]}"


